/**
 * 左侧树 ↔ 右侧列表的「选中契约」—— 客户 / 供应商 / 商品（以及后续仓库、员工）共用。
 *
 * ## 为什么要有这个文件
 *
 * 改造前，`null` 同时表示两件互相矛盾的事：
 *   ① 「我还没选任何分类」（页面刚打开）
 *   ② 「我点了『全部』」
 * 于是页面一打开就默认把全部数据刷出来 —— 左树成了装饰，右表又长又乱，
 * 用户根本不知道自己看的是"全部"还是"某个分类"。
 *
 * 现在拆成三种状态，语义唯一：
 *
 *   ┌────────────────┬──────────────────────────────────────────────┐
 *   │ 值              │ 含义与右侧列表                                 │
 *   ├────────────────┼──────────────────────────────────────────────┤
 *   │ `null`         │ 还没选（初始态）→ **列表为空**，提示去左侧点一下   │
 *   │ `ALL`          │ 点了「全部」→ 不过滤，显示全量                   │
 *   │ 具体 id / 未分类 │ 点具体分类 → 显示该分类（含子孙）下的数据          │
 *   └────────────────┴──────────────────────────────────────────────┘
 *
 * 这样"用户到底选了没有"不再靠猜，空表也有明确的原因与指引。
 *
 * ⚠️ 只做纯函数与常量，不引入任何 React / 组件依赖 —— 方便被 node --test 直接跑。
 */

/** 「全部」被点选。用字符串而不是 Symbol：要能进 URL / localStorage / 比较日志 */
export const ALL = '__all__';

/** 是否已经做过选择（null / undefined = 还没选） */
export function isPicked(value) {
  return value !== null && value !== undefined;
}

/** 是否选的「全部」 */
export function isAll(value) {
  return value === ALL;
}

/**
 * 「请在左侧选择一个分类」的空态。
 *
 * 一定要说明**怎么解除**：只写"没有数据"会让人以为库里空了，
 * 而真实原因是"你还没点左边的树"。
 *
 * @param {string} noun   名词：客户 / 供应商 / 商品
 */
export function pickPrompt(noun = '分类') {
  return {
    variant: 'filter',
    title: '请在左侧选择一个分类',
    description: `点左侧的「全部${noun}」可以看全部，点某个分类只看这一类。`,
  };
}
